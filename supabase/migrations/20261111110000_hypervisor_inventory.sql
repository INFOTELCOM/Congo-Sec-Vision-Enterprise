-- Additive migration: isolated hypervisor inventory in the existing SOC schema.
-- No existing SOC or public table is altered.
create table if not exists soc.hypervisor_inventory (
  id bigint generated by default as identity primary key,
  provider text not null check (provider in ('vmware','proxmox','virtualbox','hyperv')),
  vm_id text not null,
  name text not null default '',
  state text not null default 'unknown',
  metadata jsonb not null default '{}'::jsonb,
  last_seen timestamptz not null default now(),
  updated_by text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint hypervisor_inventory_provider_vm_unique unique (provider, vm_id)
);

alter table soc.hypervisor_inventory enable row level security;

grant usage on schema soc to authenticated;
revoke all on table soc.hypervisor_inventory from anon;
grant select, insert, update on table soc.hypervisor_inventory to authenticated;
grant usage, select on sequence soc.hypervisor_inventory_id_seq to authenticated;

drop policy if exists hypervisor_inventory_read_soc_roles on soc.hypervisor_inventory;
create policy hypervisor_inventory_read_soc_roles
  on soc.hypervisor_inventory for select to authenticated
  using (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'csv_role',
             auth.jwt() -> 'app_metadata' ->> 'role', '') in
      ('admin','analyst','viewer','incident_responder')
    or coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb)
      ?| array['admin','analyst','viewer','incident_responder']
  );

drop policy if exists hypervisor_inventory_write_analysts on soc.hypervisor_inventory;
create policy hypervisor_inventory_write_analysts
  on soc.hypervisor_inventory for insert to authenticated
  with check (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'csv_role',
             auth.jwt() -> 'app_metadata' ->> 'role', '') in ('admin','analyst')
    or coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb)
      ?| array['admin','analyst']
  );

drop policy if exists hypervisor_inventory_update_analysts on soc.hypervisor_inventory;
create policy hypervisor_inventory_update_analysts
  on soc.hypervisor_inventory for update to authenticated
  using (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'csv_role',
             auth.jwt() -> 'app_metadata' ->> 'role', '') in ('admin','analyst')
    or coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb)
      ?| array['admin','analyst']
  )
  with check (
    coalesce(auth.jwt() -> 'app_metadata' ->> 'csv_role',
             auth.jwt() -> 'app_metadata' ->> 'role', '') in ('admin','analyst')
    or coalesce(auth.jwt() -> 'app_metadata' -> 'roles', '[]'::jsonb)
      ?| array['admin','analyst']
  );
