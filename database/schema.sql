-- Congo Sec Vision Enterprise — Supabase PostgreSQL foundation
-- Private schema: accessed only by trusted server-side components.
-- Do not expose the service_role key in web or Android clients.

create schema if not exists soc;
revoke all on schema soc from public, anon, authenticated;
grant usage on schema soc to service_role;

create table if not exists soc.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default '',
  role text not null default 'analyst'
    check (role in ('admin','analyst','viewer','incident_responder')),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists soc.assets (
  id text primary key, hostname text not null, platform text,
  ip_addresses jsonb not null default '[]'::jsonb,
  inventory jsonb not null default '{}'::jsonb,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now()
);
create table if not exists soc.agent_tokens (
  token_hash text primary key,
  asset_id text not null references soc.assets(id) on delete cascade,
  created_at timestamptz not null default now(), last_used_at timestamptz
);
create table if not exists soc.events (
  id bigint generated by default as identity primary key,
  asset_id text references soc.assets(id) on delete set null,
  severity text, category text, message text,
  created_at timestamptz not null default now(), raw jsonb
);
create table if not exists soc.vulnerabilities (
  id bigint generated by default as identity primary key,
  asset_id text references soc.assets(id) on delete cascade,
  cve_id text, severity text, title text, status text not null default 'open',
  source text, created_at timestamptz not null default now(),
  unique(asset_id,cve_id)
);
create table if not exists soc.software (
  id bigint generated by default as identity primary key,
  asset_id text references soc.assets(id) on delete cascade,
  name text, version text, vendor text,
  collected_at timestamptz not null default now()
);
create table if not exists soc.log_findings (
  id bigint generated by default as identity primary key,
  asset_id text references soc.assets(id) on delete set null,
  severity text, rule_id text, title text, details text,
  created_at timestamptz not null default now()
);
create table if not exists soc.incidents (
  id bigint generated by default as identity primary key,
  title text not null, description text not null default '',
  severity text not null default 'medium', status text not null default 'open',
  assignee text not null default '', source text not null default 'manual',
  asset_id text references soc.assets(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(), closed_at timestamptz
);
create table if not exists soc.audit_logs (
  id bigint generated by default as identity primary key,
  actor text not null, action text not null,
  target text not null default '', details text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists soc.team_members (
  id bigint generated by default as identity primary key,
  user_id uuid unique references auth.users(id) on delete set null,
  username text unique not null, display_name text not null,
  role text not null check (role in ('admin','analyst','viewer','incident_responder')),
  active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists soc.approvals (
  id bigint generated by default as identity primary key,
  title text not null, description text not null,
  target text not null default '', action_type text not null default 'manual',
  status text not null default 'pending', requested_by text not null,
  reviewed_by text not null default '', created_at timestamptz not null default now(),
  reviewed_at timestamptz
);
create table if not exists soc.workflows (
  id bigint generated by default as identity primary key,
  name text not null, description text not null default '',
  trigger_type text not null default 'manual', enabled boolean not null default false,
  requires_approval boolean not null default true, created_at timestamptz not null default now()
);

create index if not exists idx_assets_last_seen on soc.assets(last_seen desc);
create index if not exists idx_agent_tokens_asset_id on soc.agent_tokens(asset_id);
create index if not exists idx_events_created_at on soc.events(created_at desc);
create index if not exists idx_events_asset_id on soc.events(asset_id);
create index if not exists idx_vulnerabilities_status on soc.vulnerabilities(status);
create index if not exists idx_software_asset_id on soc.software(asset_id);
create index if not exists idx_findings_created_at on soc.log_findings(created_at desc);
create index if not exists idx_log_findings_asset_id on soc.log_findings(asset_id);
create index if not exists idx_incidents_status on soc.incidents(status);
create index if not exists idx_incidents_asset_id on soc.incidents(asset_id);
create index if not exists idx_audit_created_at on soc.audit_logs(created_at desc);

alter table soc.profiles enable row level security;
alter table soc.assets enable row level security;
alter table soc.agent_tokens enable row level security;
alter table soc.events enable row level security;
alter table soc.vulnerabilities enable row level security;
alter table soc.software enable row level security;
alter table soc.log_findings enable row level security;
alter table soc.incidents enable row level security;
alter table soc.audit_logs enable row level security;
alter table soc.team_members enable row level security;
alter table soc.approvals enable row level security;
alter table soc.workflows enable row level security;

revoke all on all tables in schema soc from public, anon, authenticated;
grant select, insert, update, delete on all tables in schema soc to service_role;
grant usage, select on all sequences in schema soc to service_role;
alter default privileges in schema soc revoke all on tables from public, anon, authenticated;
alter default privileges in schema soc grant select, insert, update, delete on tables to service_role;
alter default privileges in schema soc grant usage, select on sequences to service_role;

-- AI SOC worker assignment and report history
create table if not exists soc.ai_agents (
  id bigint generated by default as identity primary key,
  asset_id text not null unique references soc.assets(id) on delete cascade,
  name text not null,
  status text not null default 'active' check (status in ('active','paused','error')),
  created_at timestamptz not null default now(),
  last_analysis_at timestamptz,
  last_report_id bigint
);
create table if not exists soc.ai_reports (
  id bigint generated by default as identity primary key,
  asset_id text not null references soc.assets(id) on delete cascade,
  report_type text not null,
  summary jsonb not null default '{}'::jsonb,
  findings jsonb not null default '[]'::jsonb,
  events_reviewed integer not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists idx_ai_agents_status on soc.ai_agents(status);
create index if not exists idx_ai_reports_asset_created on soc.ai_reports(asset_id,created_at desc);
alter table soc.ai_agents enable row level security;
alter table soc.ai_reports enable row level security;
revoke all on soc.ai_agents, soc.ai_reports from public, anon, authenticated;
grant select,insert,update,delete on soc.ai_agents, soc.ai_reports to service_role;
grant usage,select on sequence soc.ai_agents_id_seq to service_role;
grant usage,select on sequence soc.ai_reports_id_seq to service_role;
