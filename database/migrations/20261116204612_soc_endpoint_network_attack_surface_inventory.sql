-- Endpoint inventory, network exposure and malware telemetry.
-- Additive only: preserve existing assets, users, sessions and historical SOC data.

alter table public.assets
  add column if not exists os_install_date date,
  add column if not exists os_install_date_source text not null default '',
  add column if not exists os_install_date_confidence numeric(4,3);

alter table public.software
  add column if not exists installed_at timestamptz,
  add column if not exists install_location text not null default '',
  add column if not exists install_scope text not null default '',
  add column if not exists package_id text not null default '',
  add column if not exists last_seen timestamptz not null default now();

create table if not exists public.soc_scan_runs (
  id uuid primary key default gen_random_uuid(),
  scan_type text not null check (scan_type in ('network_discovery','port_scan','endpoint_inventory','antivirus','malware','vulnerability')),
  target text not null default '',
  status text not null default 'queued' check (status in ('queued','running','completed','partial','failed','cancelled')),
  started_by text not null default 'system',
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  summary jsonb not null default '{}'::jsonb,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.soc_network_devices (
  id uuid primary key default gen_random_uuid(),
  ip_address inet not null,
  network_cidr cidr not null,
  mac_address text not null default '',
  hostname text not null default '',
  vendor text not null default '',
  device_type text not null default 'unknown',
  os_guess text not null default '',
  status text not null default 'observed' check (status in ('active','inactive','unreachable','observed','unknown')),
  discovery_method text not null default 'authorized_lan_discovery',
  confidence numeric(4,3) not null default 0.5 check (confidence >= 0 and confidence <= 1),
  authorized_scope boolean not null default true,
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  last_scan_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  unique (network_cidr, ip_address)
);

create table if not exists public.soc_listening_ports (
  id bigint generated by default as identity primary key,
  network_device_id uuid references public.soc_network_devices(id) on delete cascade,
  asset_id text references public.assets(id) on delete set null,
  scan_run_id uuid references public.soc_scan_runs(id) on delete set null,
  ip_address inet not null,
  protocol text not null check (protocol in ('tcp','udp')),
  port integer not null check (port between 1 and 65535),
  state text not null default 'open',
  service_name text not null default '',
  product text not null default '',
  version text not null default '',
  banner text not null default '',
  cpe text not null default '',
  confidence numeric(4,3) not null default 0.5 check (confidence >= 0 and confidence <= 1),
  source text not null default 'authorized_port_scan',
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  unique (ip_address, protocol, port)
);

create table if not exists public.soc_endpoint_protection (
  id bigint generated by default as identity primary key,
  asset_id text not null references public.assets(id) on delete cascade,
  provider text not null,
  product_version text not null default '',
  antivirus_enabled boolean,
  antispyware_enabled boolean,
  real_time_enabled boolean,
  behavior_monitoring_enabled boolean,
  definitions_version text not null default '',
  definitions_updated_at timestamptz,
  last_scan_at timestamptz,
  last_scan_type text not null default '',
  last_scan_status text not null default 'unknown',
  health_status text not null default 'unknown',
  raw_details jsonb not null default '{}'::jsonb,
  observed_at timestamptz not null default now(),
  unique (asset_id, provider)
);

create table if not exists public.soc_malware_detections (
  id bigint generated by default as identity primary key,
  asset_id text references public.assets(id) on delete set null,
  network_device_id uuid references public.soc_network_devices(id) on delete set null,
  scan_run_id uuid references public.soc_scan_runs(id) on delete set null,
  detection_source text not null,
  threat_name text not null default 'Unclassified detection',
  threat_type text not null default 'unknown',
  severity text not null default 'medium' check (severity in ('critical','high','medium','low','info')),
  confidence numeric(4,3) not null default 0.5 check (confidence >= 0 and confidence <= 1),
  file_path text not null default '',
  sha256 text,
  action_taken text not null default 'none',
  status text not null default 'open' check (status in ('open','quarantined','removed','allowed','false_positive','resolved')),
  detected_at timestamptz not null default now(),
  resolved_at timestamptz,
  evidence jsonb not null default '{}'::jsonb,
  check (sha256 is null or sha256 ~ '^[0-9a-fA-F]{64}$')
);

alter table public.vulnerabilities
  add column if not exists network_device_id uuid references public.soc_network_devices(id) on delete set null,
  add column if not exists ip_address inet,
  add column if not exists port integer check (port is null or port between 1 and 65535),
  add column if not exists service_name text not null default '',
  add column if not exists cpe text not null default '',
  add column if not exists cvss_score numeric(4,1),
  add column if not exists cvss_version text not null default '',
  add column if not exists cvss_vector text not null default '',
  add column if not exists cwe_ids text[] not null default '{}',
  add column if not exists epss_score numeric(8,7),
  add column if not exists epss_percentile numeric(8,7),
  add column if not exists known_exploited boolean not null default false,
  add column if not exists published_at timestamptz,
  add column if not exists last_modified_at timestamptz,
  add column if not exists cpe_matches jsonb not null default '[]'::jsonb,
  add column if not exists references_json jsonb not null default '[]'::jsonb,
  add column if not exists affected_json jsonb not null default '[]'::jsonb,
  add column if not exists sources_json jsonb not null default '[]'::jsonb;

create index if not exists idx_soc_devices_ip on public.soc_network_devices(ip_address);
create index if not exists idx_soc_devices_last_seen on public.soc_network_devices(last_seen desc);
create index if not exists idx_soc_ports_ip_port on public.soc_listening_ports(ip_address, port);
create index if not exists idx_soc_ports_device on public.soc_listening_ports(network_device_id, last_seen desc);
create index if not exists idx_soc_protection_asset on public.soc_endpoint_protection(asset_id, observed_at desc);
create index if not exists idx_soc_malware_asset on public.soc_malware_detections(asset_id, detected_at desc);
create index if not exists idx_soc_malware_sha on public.soc_malware_detections(sha256) where sha256 is not null;
create index if not exists idx_vuln_network_device on public.vulnerabilities(network_device_id);
create index if not exists idx_vuln_cvss_kev on public.vulnerabilities(known_exploited desc, cvss_score desc);

