-- Extend the SOC database for richer asset-scoped CVE triage and network discovery.
alter table soc.vulnerabilities
  add column if not exists software_name text not null default '',
  add column if not exists software_version text not null default '',
  add column if not exists vendor text not null default '',
  add column if not exists match_confidence text not null default 'candidate',
  add column if not exists cve_url text not null default '',
  add column if not exists cvss_score double precision,
  add column if not exists cvss_version text not null default '',
  add column if not exists cvss_vector text not null default '',
  add column if not exists cwe_ids jsonb not null default '[]'::jsonb,
  add column if not exists cpe_matches jsonb not null default '[]'::jsonb,
  add column if not exists references_json jsonb not null default '[]'::jsonb,
  add column if not exists epss_score double precision,
  add column if not exists epss_percentile double precision,
  add column if not exists known_exploited boolean not null default false,
  add column if not exists published_at timestamptz,
  add column if not exists last_modified_at timestamptz,
  add column if not exists vuln_status text not null default '',
  add column if not exists sources_json jsonb not null default '[]'::jsonb,
  add column if not exists ssvc_json jsonb not null default '[]'::jsonb,
  add column if not exists affected_json jsonb not null default '[]'::jsonb,
  add column if not exists assigned_to text not null default '',
  add column if not exists tags_json jsonb not null default '[]'::jsonb;
create index if not exists soc_vulnerabilities_cve_id_idx on soc.vulnerabilities(cve_id);
create index if not exists soc_vulnerabilities_known_exploited_idx on soc.vulnerabilities(known_exploited) where known_exploited;
create table if not exists soc.network_discoveries (
  id bigint generated by default as identity primary key,
  cidr cidr not null,
  ip_address inet not null,
  hostname text not null default '',
  status text not null default 'reachable',
  source text not null default 'icmp',
  first_seen timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  unique(cidr, ip_address),
  check (ip_address <<= cidr)
);
create index if not exists network_discoveries_cidr_idx on soc.network_discoveries(cidr);
create index if not exists network_discoveries_last_seen_idx on soc.network_discoveries(last_seen desc);
create table if not exists soc.cve_history (
  id bigint generated by default as identity primary key,
  vulnerability_id bigint not null references soc.vulnerabilities(id) on delete cascade,
  cve_id text not null,
  event_type text not null,
  details text not null default '',
  created_at timestamptz not null default now()
);
create index if not exists cve_history_cve_created_idx on soc.cve_history(cve_id, created_at desc);
create table if not exists soc.cve_subscriptions (
  id bigint generated by default as identity primary key,
  vendor text not null default '',
  product text not null default '',
  asset_id text not null default '',
  active boolean not null default true,
  created_by text not null,
  created_at timestamptz not null default now(),
  unique(vendor, product, asset_id)
);
create table if not exists soc.cve_notifications (
  id bigint generated by default as identity primary key,
  subscription_id bigint not null references soc.cve_subscriptions(id) on delete cascade,
  vulnerability_id bigint not null references soc.vulnerabilities(id) on delete cascade,
  cve_id text not null,
  event_type text not null,
  title text not null default '',
  severity text not null default 'unknown',
  created_at timestamptz not null default now(),
  read_at timestamptz,
  unique(subscription_id, vulnerability_id, event_type)
);
alter table soc.network_discoveries enable row level security;
alter table soc.cve_history enable row level security;
alter table soc.cve_subscriptions enable row level security;
alter table soc.cve_notifications enable row level security;
grant select, insert, update, delete on soc.network_discoveries, soc.cve_history, soc.cve_subscriptions, soc.cve_notifications to authenticated;
grant usage, select on sequence soc.network_discoveries_id_seq, soc.cve_history_id_seq, soc.cve_subscriptions_id_seq, soc.cve_notifications_id_seq to authenticated;
create policy network_discoveries_read_soc_roles on soc.network_discoveries for select to authenticated
  using (soc.has_soc_role(array['admin','analyst','viewer','incident_responder']));
create policy network_discoveries_insert_analysts on soc.network_discoveries for insert to authenticated
  with check (soc.has_soc_role(array['admin','analyst']));
create policy network_discoveries_update_analysts on soc.network_discoveries for update to authenticated
  using (soc.has_soc_role(array['admin','analyst'])) with check (soc.has_soc_role(array['admin','analyst']));
